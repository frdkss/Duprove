const test = require('node:test')
const assert = require('node:assert/strict')
const { DatabaseSync } = require('node:sqlite')
const fs = require('node:fs/promises')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const { CatalogService, CATALOG_AGE } = require('../.verification/tests/electron/services/catalog-service.js')
const { isCatalogRequest } = require('../.verification/tests/contracts/catalog.js')

async function fixture(t, count = 1051) {
  const directory = await fs.mkdtemp(path.join(__dirname, '../.verification/catalog-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const source = path.join(directory, 'work.sqlite')
  const db = new DatabaseSync(source)
  db.exec(`CREATE TABLE files(path TEXT,identity TEXT,root INTEGER,size INTEGER,mtime INTEGER,ctime INTEGER,hash TEXT,gid INTEGER);
    CREATE TABLE content_files(path TEXT,status TEXT); CREATE TABLE content_matches(left_path TEXT,right_path TEXT,kind TEXT); BEGIN;`)
  const insert = db.prepare('INSERT INTO files VALUES(?,?,?,?,?,?,?,?)')
  for (let i = 1; i <= count; i++) insert.run(path.join(directory, `${i % 2 ? 'disk-a' : 'disk-b'}-${i}.txt`), `identity:${i}`, i % 2, 3, 134000000000000001n, 134000000000000002n, 'a'.repeat(64), 1)
  insert.run(path.join(directory, 'singleton.txt'), 'singleton', 0, 9, 1, 2, 'b'.repeat(64), 2)
  const names = [1, 2, 3].map(i => path.join(directory, `${i % 2 ? 'disk-a' : 'disk-b'}-${i}.txt`))
  for (const name of names) db.prepare('INSERT INTO content_files VALUES(?,?)').run(name, 'ready')
  for (let i = 0; i < 2; i++) db.prepare('INSERT INTO content_matches VALUES(?,?,?)').run(names[i], names[i + 1], 'text')
  db.exec('COMMIT'); db.close()
  const analysisId = randomUUID()
  const catalog = new CatalogService(directory)
  await catalog.capture(source, analysisId, [directory], true)
  return { directory, source, catalog, analysisId, names, count }
}

test('catalog retains precise metadata, large cross-root groups and separate warning pairs after work cleanup', async t => {
  const f = await fixture(t)
  await fs.unlink(f.source)
  const restored = new CatalogService(f.directory)
  const info = await restored.request({ action: 'info', analysisId: f.analysisId })
  assert.deepEqual(info.groups, { exact: 1, warn_text: 2, warn_image: 0 })
  assert.equal(info.files, f.count)
  const groups = await restored.request({ action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: 0 })
  assert.equal(groups.items[0].count, f.count)
  assert.equal(groups.items[0].originalId, null)
  assert.equal(groups.items[0].name, 'disk-a-1.txt', 'Names remain available from an existing catalog after work cleanup')
  const members = await restored.request({ action: 'members', analysisId: f.analysisId, groupId: 'e:1', offset: 1025 })
  assert.equal(members.total, f.count); assert.equal(members.items.length, 25)
  assert.equal(members.items[0].id, 1026)
  assert.equal(members.items[0].availability, 'missing')
  await fs.writeFile(members.items[0].path, 'abc')
  assert.equal((await restored.request({ action: 'members', analysisId: f.analysisId, groupId: 'e:1', offset: 1025 })).items[0].availability, 'available')
  const db = await restored.open(f.analysisId)
  assert.equal(db.prepare('SELECT mtime FROM files LIMIT 1').get().mtime, '134000000000000001')
  assert.equal(db.prepare('PRAGMA max_page_count').get().max_page_count * 4096, 128 * 1024 * 1024,
    'the storage limit also applies after reopening the catalog for decisions and trash intents')
  db.close()
  const warn = await restored.request({ action: 'groups', analysisId: f.analysisId, kind: 'warn_text', offset: 0 })
  assert.ok(warn.items.every(g => g.count === 2 && g.kind === 'warn_text'))
  assert.equal(warn.items[0].name, 'disk-a-1.txt')
})

test('group names use the most frequent complete filename across every member, with stable ties', async t => {
  const f = await fixture(t, 60)
  const source = new DatabaseSync(f.source)
  for (let i = 26; i <= 60; i++) source.prepare('UPDATE files SET path=? WHERE rowid=?').run(path.join(f.directory, `copy-${i}`, 'отчёт.final.tar.gz'), i)
  const insert = source.prepare('INSERT INTO files VALUES(?,?,?,?,?,?,?,?)')
  for (const [gid, names] of [[3, ['zzz.txt', 'aaa.csv']], [4, ['.env', '.env']]]) {
    names.forEach((name, i) => insert.run(path.join(f.directory, `${gid}-${i}`, name), `${gid}:${i}`, 0, 3, 1, 2, 'c'.repeat(64), gid))
  }
  source.close()
  await f.catalog.capture(f.source, f.analysisId, [f.directory], true)
  await fs.unlink(f.source)
  const restored = new CatalogService(f.directory)
  const groups = await restored.request({ action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: 0 })
  assert.equal(groups.items.find(g => g.id === 'e:1').name, 'отчёт.final.tar.gz', 'The winning name exists only beyond the first member page')
  assert.equal(groups.items.find(g => g.id === 'e:3').name, 'aaa.csv', 'Ties are independent of insertion order')
  assert.equal(groups.items.find(g => g.id === 'e:4').name, '.env')
  await restored.request({ action: 'original', analysisId: f.analysisId, groupId: 'e:1', fileId: 1 })
  const refreshed = await restored.request({ action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: 0 })
  assert.equal(refreshed.items[0].name, 'отчёт.final.tar.gz', 'Selecting an original does not change the group name')
  assert.equal(refreshed.items[0].originalId, 1)
})

test('catalog rejects injected paths, SQL, wrong analyses, missing and expired results', async t => {
  const f = await fixture(t, 4)
  for (const v of [null, { action: 'info', analysisId: f.analysisId, path: 'arbitrary' },
    { action: 'members', analysisId: f.analysisId, groupId: "e:1' OR 1=1", offset: 0 },
    { action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: -1 },
    { action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: 0.5 }]) {
    assert.equal(isCatalogRequest(v), false)
    await assert.rejects(f.catalog.request(v), /INVALID_CATALOG_REQUEST/)
  }
  await assert.rejects(f.catalog.request({ action: 'info', analysisId: randomUUID() }), /CATALOG_UNAVAILABLE/)
  await f.catalog.capture(f.source, randomUUID(), [f.directory], false)
  await assert.rejects(f.catalog.request({ action: 'info', analysisId: f.analysisId }), /CATALOG_UNAVAILABLE/)
  await f.catalog.capture(f.source, f.analysisId, [f.directory], false)
  const db = await f.catalog.open(f.analysisId)
  db.prepare('UPDATE meta SET created_at=?').run(Date.now() - CATALOG_AGE - 1); db.close()
  await assert.rejects(f.catalog.request({ action: 'info', analysisId: f.analysisId }), /CATALOG_EXPIRED/)
  await assert.rejects(fs.stat(f.catalog.file), /ENOENT/)
  await assert.rejects(f.catalog.request({ action: 'info', analysisId: f.analysisId }), /CATALOG_UNAVAILABLE/)
})

test('original selection is explicit, persists across restart and protects overlapping pairs', async t => {
  const f = await fixture(t, 4)
  const request = { action: 'original', analysisId: f.analysisId, groupId: 'e:1', fileId: 1 }
  await f.catalog.request(request)
  const restored = new CatalogService(f.directory)
  assert.equal((await restored.request({ action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: 0 })).items[0].originalId, 1)
  let members = await restored.request({ action: 'members', analysisId: f.analysisId, groupId: 't:1', offset: 0 })
  assert.equal(members.items[0].protected, true)
  assert.equal(members.items[0].decision, 'keep')
  await restored.request({ ...request, fileId: 2 })
  members = await restored.request({ action: 'members', analysisId: f.analysisId, groupId: 'e:1', offset: 0 })
  assert.equal(members.items.filter(f => f.protected).length, 1)
  await restored.request({ ...request, fileId: null })
  assert.equal((await restored.request({ action: 'groups', analysisId: f.analysisId, kind: 'exact', offset: 0 })).items[0].originalId, null)
  await assert.rejects(restored.request({ ...request, fileId: 99999 }), /FILE_UNAVAILABLE/)
  await restored.capture(f.source, randomUUID(), [f.directory], true)
  await assert.rejects(restored.request(request), /CATALOG_UNAVAILABLE/)
})

test('decisions preserve evidence, warn deletion requires both previews and originals protect across groups', async t => {
  const f = await fixture(t, 4)
  const inspect = async (_exe, request) => ({ status: 'ready', kind: 'text', text: '<script>literal preview</script>', sha256: 'c'.repeat(64) })
  const catalog = new CatalogService(f.directory, 'test-inspector', inspect)
  const decision = { action: 'decision', analysisId: f.analysisId, groupId: 'e:1', fileId: 2, decision: 'delete', reviewed: false }
  await assert.rejects(catalog.request(decision), /ORIGINAL_REQUIRED/)
  await catalog.request({ action: 'original', analysisId: f.analysisId, groupId: 'e:1', fileId: 1 })
  await catalog.request(decision)
  await assert.rejects(catalog.request({ ...decision, fileId: 1 }), /ORIGINAL_PROTECTED/)
  await catalog.request({ action: 'original', analysisId: f.analysisId, groupId: 't:1', fileId: 2 })
  await assert.rejects(catalog.request({ ...decision, groupId: 't:1', fileId: 1, reviewed: true }), /ORIGINAL_PROTECTED/)
  await catalog.request({ action: 'original', analysisId: f.analysisId, groupId: 't:1', fileId: 1 })
  await assert.rejects(catalog.request({ ...decision, groupId: 't:1', reviewed: true }), /MANUAL_REVIEW_REQUIRED/)
  const pair = await catalog.request({ action: 'compare', analysisId: f.analysisId, groupId: 't:1', fileId: 2 })
  assert.equal(pair.original.id, 1); assert.equal(pair.candidate.id, 2)
  assert.equal(pair.original.sha256, undefined, 'native evidence stays internal')
  await assert.rejects(catalog.request({ ...decision, groupId: 't:1' }), /MANUAL_REVIEW_REQUIRED/)
  await catalog.request({ ...decision, groupId: 't:1', reviewed: true })
  const restored = new CatalogService(f.directory)
  const members = await restored.request({ action: 'members', analysisId: f.analysisId, groupId: 't:1', offset: 0 })
  assert.equal(members.items[1].decision, 'delete')
  const db = await restored.open(f.analysisId)
  assert.equal(db.prepare('SELECT hash FROM files WHERE id=2').get().hash, 'a'.repeat(64), 'user decisions never rewrite scan hashes')
  db.close()
  await assert.rejects(catalog.request({ ...decision, decision: 'trashed' }), /INVALID_CATALOG_REQUEST/)
  await assert.rejects(catalog.request({ ...decision, decision: { toString: null, valueOf: null } }), /INVALID_CATALOG_REQUEST/)
  await catalog.request({ action: 'original', analysisId: f.analysisId, groupId: 't:1', fileId: 2 })
  await catalog.request({ action: 'original', analysisId: f.analysisId, groupId: 't:1', fileId: 1 })
  await assert.rejects(catalog.request({ ...decision, groupId: 't:1', reviewed: true }), /MANUAL_REVIEW_REQUIRED/)
})
