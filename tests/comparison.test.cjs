const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const JSZip = require('jszip')
const { isComparisonRequest, isComparisonFileRequest, comparisonColumns, viewerKind } = require('../.verification/tests/contracts/comparison.js')
const { decodeEditorText, checkArchiveBudget } = require('../.verification/tests/src/window/ComparisonWindow/viewer-utils.js')
const { previewResponse } = require('../.verification/tests/electron/services/preview-stream.js')

test('comparison accepts catalog IDs, any number up to the page budget and responsive 2/3/4 document layouts', () => {
  const request = { analysisId: randomUUID(), groupId: 'e:1', fileIds: [1, 2, 3, 4, 5] }
  assert.ok(isComparisonRequest(request))
  for (const value of [{ ...request, path: 'injected.py' }, { ...request, fileIds: [] }, { ...request, fileIds: [1, 1] }, { ...request, fileIds: [1.1] }]) assert.equal(isComparisonRequest(value), false)
  assert.ok(isComparisonFileRequest({ analysisId: request.analysisId, groupId: request.groupId, fileId: 1, sessionId: randomUUID() }))
  assert.equal(comparisonColumns(1920, 8), 4)
  assert.equal(comparisonColumns(1366, 8), 3)
  assert.equal(comparisonColumns(1280, 8), 3)
  assert.equal(comparisonColumns(1000, 8), 2)
  assert.equal(comparisonColumns(1920, 2), 2)
  assert.equal(viewerKind('script.py'), 'text')
  for (const [file, kind] of [['x.pdf','pdf'],['x.doc','doc'],['x.docx','docx'],['x.xlsx','sheet'],['x.ods','sheet'],['x.mp3','audio'],['x.tiff','image']]) assert.equal(viewerKind(file), kind)
})
test('text editor decodes source files and UTF16, but rejects executable binary data', () => {
  const source = 'print("Привет")\n<script>globalThis.EXECUTED=true</script>'
  assert.equal(decodeEditorText(Buffer.from(source)).text, source)
  assert.equal(globalThis.EXECUTED, undefined)
  assert.equal(decodeEditorText(Buffer.concat([Buffer.from([255,254]),Buffer.from('Привет','utf16le')])).text, 'Привет')
  assert.throws(() => decodeEditorText(Buffer.from([77,90,0,0,1,2,3,0,0,0])), /BINARY_FILE/)
})
test('compressed document budget rejects a ZIP bomb before a viewer inflates it', async () => {
  const zip = new JSZip();zip.file('word/document.xml', 'x'.repeat(2 * 1024 ** 2))
  const bytes = await zip.generateAsync({ type: 'uint8array', compression: 'DEFLATE' })
  assert.throws(() => checkArchiveBudget(bytes, 1024), /DOCUMENT_LIMIT/)
  assert.doesNotThrow(() => checkArchiveBudget(bytes))
})
test('private preview stream supports full files, byte ranges, suffixes, HEAD and invalid ranges', async t => {
  const directory = await fs.mkdtemp(path.join(__dirname, '../.verification/preview-stream-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const file = path.join(directory, 'snapshot.bin');await fs.writeFile(file, '0123456789')
  const get = (range, method = 'GET') => previewResponse(new Request('duprove-preview://session/1', { method, headers: range ? { Range: range } : {} }), file, 'audio/wav')
  assert.equal(await (await get()).text(), '0123456789')
  const range = await get('bytes=2-5');assert.equal(range.status,206);assert.equal(range.headers.get('Content-Range'),'bytes 2-5/10');assert.equal(await range.text(),'2345')
  assert.equal(await (await get('bytes=-3')).text(), '789')
  assert.equal(await (await get('bytes=8-999')).text(), '89')
  for (const range of ['bytes=99-', 'bytes=-0', 'bytes=5-2', 'bytes=0-1,4-5']) assert.equal((await get(range)).status, 416)
  const head = await get(null, 'HEAD');assert.equal(head.headers.get('Content-Length'),'10');assert.equal(await head.text(),'')
})
