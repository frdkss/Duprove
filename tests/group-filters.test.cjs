const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const { DatabaseSync } = require('node:sqlite')
const { groupSearch, groupSelection } = require('../.verification/tests/contracts/group-filters.js')
const { CatalogService } = require('../.verification/tests/electron/services/catalog-service.js')
const { isCatalogRequest, isTrashRequest } = require('../.verification/tests/contracts/catalog.js')

test('group search supports substrings, exact quoted names and Unicode filename globs without regex syntax', () => {
  assert.ok(groupSearch('PDF')('Отчёт.pdf'))
  assert.ok(groupSearch('привет')('Копия ПРИВЕТ.txt'))
  assert.ok(groupSearch('"отчёт.txt"')('Отчёт.txt'))
  assert.equal(groupSearch('"отчёт.txt"')('копия-отчёт.txt'), false)
  const matches = groupSearch('"при"*.tx*')
  for (const file of ['привет.txt', 'пример.txz', 'при.tx']) assert.ok(matches(file), file)
  for (const file of ['копияпривет.txt', 'пример.pdf', 'приветxtxt']) assert.equal(matches(file), false, file)
  assert.ok(groupSearch('[x].txt')('[x].txt'))
  assert.equal(groupSearch('[x].txt')('x.txt'), false)
  assert.ok(groupSearch('*')('любое имя без расширения'))
  assert.throws(() => groupSearch('"при'), /FILTER_QUERY_UNCLOSED/)
  assert.equal(groupSearch('*a'.repeat(100) + 'z')('a'.repeat(255)), false)
})

test('selection rules retain search-scoped select-all, later exclusions and manual choices across searches', () => {
  const rules = [{ query: '*.txt', checked: true }, { id: 'e:2', checked: false }, { id: 'e:3', checked: true }]
  const selected = groupSelection(rules)
  assert.ok(selected('e:1', 'a.txt')); assert.equal(selected('e:2', 'b.txt'), false)
  assert.ok(selected('e:3', 'c.pdf')); assert.equal(selected('e:4', 'd.pdf'), false)
  const cleared = groupSelection([...rules, { query: '*.txt', checked: false }])
  assert.equal(cleared('e:1', 'a.txt'), false); assert.ok(cleared('e:3', 'c.pdf'))
  assert.ok(groupSelection([...rules, { query: '', checked: true }])('e:2', 'b.txt'))
})

test('catalog searches every group and selects unloaded matches without retrieving all IDs or file paths', async t => {
  const directory = await fs.mkdtemp(path.join(__dirname, '../.verification/group-filters-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const source = path.join(directory, 'work.sqlite'), db = new DatabaseSync(source)
  db.exec('CREATE TABLE files(path TEXT,identity TEXT,root INTEGER,size INTEGER,mtime INTEGER,ctime INTEGER,hash TEXT,gid INTEGER); BEGIN;')
  const names = ['привет.txt', 'пример.txz', 'копияпривет.txt', 'Отчёт.PDF', ...Array.from({ length: 80 }, (_, i) => `группа-${i}.txt`)]
  const insert = db.prepare('INSERT INTO files VALUES(?,?,?,?,?,?,?,?)')
  names.forEach((name, i) => { for (let n = 0; n < 2; n++) insert.run(path.join(directory, String(n), name), `${i}:${n}`, 0, 3, 1, 2, '', i + 1) })
  db.exec('COMMIT'); db.close()
  const analysisId = randomUUID(), catalog = new CatalogService(directory)
  await catalog.capture(source, analysisId, [directory], true)
  const request = { action: 'groups', analysisId, kind: 'exact', offset: 0 }
  assert.equal((await catalog.request({ ...request, filters: [], selectedOnly: true })).total, 0)
  const found = await catalog.request({ ...request, query: '"при"*.tx*' })
  assert.deepEqual(found.items.map(group => group.name).sort(), ['привет.txt', 'пример.txz'].sort())
  const filters = [{ query: 'группа-*.txt', checked: true }]
  const first = await catalog.request({ ...request, query: 'группа-', filters })
  assert.equal(first.total, 80); assert.equal(first.selectedTotal, 80); assert.equal(first.items.length, 25)
  const tail = await catalog.request({ ...request, filters, selectedOnly: true, offset: 75 })
  assert.equal(tail.items.length, 5); assert.equal(tail.total, 80)
  const removed = tail.items[4]
  const excluded = await catalog.request({ ...request, filters: [...filters, { id: removed.id, checked: false }], selectedOnly: true })
  assert.equal(excluded.total, 79)
  assert.equal((await catalog.request({ ...request, query: 'PDF', filters })).selectedTotal, 0)
  assert.equal((await catalog.request({ ...request, query: "' OR 1=1 --" })).total, 0)
  assert.equal((await catalog.request({ ...request, query: '"Отчёт.PDF"' })).total, 1)
  for (const invalid of [{ ...request, query: 'a'.repeat(257) }, { ...request, filters: [{ id: 'e:1', checked: 'true' }] }, { ...request, selectedOnly: 1 }, { ...request, filters: [{ query: '', checked: true, path: 'injected' }] }]) assert.equal(isCatalogRequest(invalid), false)
  assert.ok(isTrashRequest({ analysisId, groupId: 'e:1', fileIds: Array.from({ length: 60 }, (_, i) => i + 1) }), 'Infinite selection is not restricted to one former 25-file page')
})
